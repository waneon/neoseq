import { readFile, writeFile } from "node:fs/promises";

const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
  throw new Error("usage: generate-contracts.mjs [--check]");
}
const check = args[0] === "--check";

const [corePort, graphSchema, syncProtocol] = await Promise.all(
  ["core-port", "graph-schema", "sync-protocol"].map(async (name) =>
    JSON.parse(await readFile(`contracts/${name}.json`, "utf8")),
  ),
);
const version = corePort.contractVersion;
const semanticEvents = corePort.semanticEvents;
const queryPlan = corePort.queryPlan;
const domainPayloads = corePort.domainPayloads;
const subprotocol = `${syncProtocol.subprotocolPrefix}${syncProtocol.protocolVersion}`;
if (
  !Array.isArray(semanticEvents) ||
  semanticEvents.length === 0 ||
  new Set(semanticEvents).size !== semanticEvents.length ||
  semanticEvents.some((event) => !/^[A-Z][A-Za-z0-9]*$/.test(event))
) {
  throw new Error("core-port semanticEvents must be unique PascalCase identifiers");
}
const domainPayloadPaths = [
  "open_graph.response.summary",
  "execute.request.command",
  "execute.response.result",
  "execute.response.changes",
  "read.response.summary",
  "read_outline.request.owner",
  "read_outline.response.outline",
];
const tsDomainTypeModules = new Map([
  ["GraphChanges", "../core-port/snapshot"],
  ["CommandEnvelope", "../core-port/commands"],
  ["CommandResult", "../core-port/commands"],
  ["GraphSummary", "../core-port/snapshot"],
  ["OutlineOwner", "../core-port/snapshot"],
  ["OutlineSnapshot", "../core-port/snapshot"],
]);
if (
  domainPayloads === null ||
  typeof domainPayloads !== "object" ||
  Array.isArray(domainPayloads) ||
  Object.keys(domainPayloads).length !== domainPayloadPaths.length ||
  domainPayloadPaths.some((path) => !Object.hasOwn(domainPayloads, path)) ||
  Object.values(domainPayloads).some(
    (type) => typeof type !== "string" || !tsDomainTypeModules.has(type),
  )
) {
  throw new Error("core-port domainPayloads must map every canonical domain field to a known type");
}
const domainPayload = (path) => domainPayloads[path];
const domainTypes = [...new Set(Object.values(domainPayloads))].sort();
const rustDomainImports = `use crate::{${domainTypes.join(", ")}};`;
const tsTypesByModule = new Map();
for (const type of domainTypes) {
  const module = tsDomainTypeModules.get(type);
  const types = tsTypesByModule.get(module) ?? [];
  types.push(type);
  tsTypesByModule.set(module, types);
}
const tsDomainImports = [...tsTypesByModule]
  .map(([module, types]) => `import type { ${types.join(", ")} } from ${JSON.stringify(module)};`)
  .join("\n");
const tsDomainExports = `export type { ${domainTypes.join(", ")} };`;
const rustSemanticEvents = semanticEvents.join(",\n    ");
const rustSemanticArms = semanticEvents
  .map((event) => `            Self::${event} => "${event}",`)
  .join("\n");
const rustSemanticValues = semanticEvents.map((event) => `    SemanticEvent::${event},`).join("\n");
const tsSemanticEvents = semanticEvents.map((event) => `  "${event}",`).join("\n");
const rustCodes = corePort.errorCodes
  .map((code) =>
    code
      .split("_")
      .map((part) => part[0].toUpperCase() + part.slice(1))
      .join(""),
  )
  .join(",\n    ");
const tsCodes = corePort.errorCodes.map((code) => `  "${code}",`).join("\n");

