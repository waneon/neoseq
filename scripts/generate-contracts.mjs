import { readFile, writeFile } from "node:fs/promises";

const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
  throw new Error("usage: generate-contracts.mjs [--check]");
}
const check = args[0] === "--check";

const [corePort, graphSchema, syncProtocol] = await Promise.all(
  ["core-port", "graph-schema", "sync-protocol"].map(async (name) =>
    JSON.parse(await readFile(`contracts/${name}.json`, "utf8")),
  ),
);
const version = corePort.contractVersion;
const subprotocol = `${syncProtocol.subprotocolPrefix}${syncProtocol.protocolVersion}`;
const rustCodes = corePort.errorCodes
  .map((code) =>
    code
      .split("_")
      .map((part) => part[0].toUpperCase() + part.slice(1))
      .join(""),
  )
  .join(",\n    ");
const tsCodes = corePort.errorCodes.map((code) => `  | "${code}"`).join("\n");

const corePortRust = `// @generated by scripts/generate-contracts.mjs; do not edit.
use serde::{Deserialize, Serialize};
use serde_json::Value;

pub const CORE_PORT_VERSION: u32 = ${version};

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct GraphLocatorDto {
    pub repository_id: String,
    pub graph_id: String,
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct StorageCapabilitiesDto {
    pub durable: bool,
    pub persisted: Option<bool>,
    pub quota_bytes: Option<u64>,
    pub usage_bytes: Option<u64>,
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct RecoveryDto {
    pub checkpoint_sequence: u64,
    pub replayed_updates: u32,
    pub quarantined_records: Vec<String>,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct OpenGraphRequest {
    pub contract_version: u32,
    pub locator: GraphLocatorDto,
    pub peer_id: u64,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct OpenGraphResponse {
    pub graph_handle: String,
    pub summary: Value,
    pub capabilities: Option<StorageCapabilitiesDto>,
    pub recovery: RecoveryDto,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct ExecuteRequest {
    pub graph_handle: String,
    pub command: Value,
    pub timeout_ms: u32,
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(tag = "status", rename_all = "snake_case")]
pub enum SaveStatusDto {
    SavedLocally {
        local_sequence: u64,
        checksum: String,
    },
    DirtyUnsaved,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct ExecuteResponse {
    pub result: Value,
    pub save_status: SaveStatusDto,
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct ReadRequest {
    pub graph_handle: String,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct ReadResponse {
    pub summary: Value,
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct ReadOutlineRequest {
    pub graph_handle: String,
    pub owner: Value,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct ReadOutlineResponse {
    pub outline: Value,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct QueryRequestDto {
    pub graph_handle: String,
    pub query: Value,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct QueryResponseDto {
    pub result: Value,
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct SubscribeRequest {
    pub graph_handle: String,
    pub after_cursor: u64,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct SubscribeResponse {
    pub events: Vec<Value>,
    pub next_cursor: u64,
    pub resync_required: bool,
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct CloseGraphRequest {
    pub graph_handle: String,
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct CloseGraphResponse {
    pub closed: bool,
}

#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum CorePortErrorCode {
    ${rustCodes},
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct CorePortError {
    pub code: CorePortErrorCode,
    pub message: String,
    pub retryable: bool,
}
`;

const corePortTypescript = `// @generated by scripts/generate-contracts.mjs; do not edit.
export const CORE_PORT_VERSION = ${version} as const;

export interface GraphLocatorDto { repository_id: string; graph_id: string; }
export interface StorageCapabilitiesDto { durable: boolean; persisted?: boolean | null; quota_bytes?: number | null; usage_bytes?: number | null; }
export interface RecoveryDto { checkpoint_sequence: number; replayed_updates: number; quarantined_records: string[]; }
export interface OpenGraphRequest { contract_version: number; locator: GraphLocatorDto; peer_id: number; }
export interface OpenGraphResponse { graph_handle: string; summary: unknown; capabilities?: StorageCapabilitiesDto | null; recovery: RecoveryDto; }
export interface ExecuteRequest { graph_handle: string; command: unknown; timeout_ms: number; }
export type SaveStatusDto = { status: "saved_locally"; local_sequence: number; checksum: string } | { status: "dirty_unsaved" };
export interface ExecuteResponse { result: unknown; save_status: SaveStatusDto; }
export interface ReadRequest { graph_handle: string; }
export interface ReadResponse { summary: unknown; }
export type OutlineOwnerDto = { kind: "page"; id: string } | { kind: "tag"; id: string };
export interface ReadOutlineRequest { graph_handle: string; owner: OutlineOwnerDto; }
export interface ReadOutlineResponse { outline: unknown; }
export type QueryEntityRef =
  | { kind: "page"; id: string }
  | { kind: "block"; owner: OutlineOwnerDto; id: string }
  | { kind: "tag"; id: string };
export type RdfTerm =
  | { kind: "iri"; value: string; entity?: QueryEntityRef | null }
  | { kind: "literal"; value: string; datatype: string; language?: string | null };
export interface QueryBudget { max_source_bytes: number; max_algebra_operators: number; max_bindings: number; max_rows: number; }
export interface SparqlQueryRequest { language: "sparql-1.1/neoseq-v1"; source: string; bindings?: Record<string, RdfTerm>; budget?: Partial<QueryBudget>; }
export type SparqlQueryResult =
  | { kind: "select"; variables: string[]; rows: Array<Record<string, RdfTerm>>; revision: number; frontier: string }
  | { kind: "ask"; value: boolean; revision: number; frontier: string };
export interface QueryRequest { graph_handle: string; query: SparqlQueryRequest; }
export interface QueryResponse { result: SparqlQueryResult; }
export interface SubscribeRequest { graph_handle: string; after_cursor: number; }
export interface SubscribeResponse { events: unknown[]; next_cursor: number; resync_required: boolean; }
export interface CloseGraphRequest { graph_handle: string; }
export interface CloseGraphResponse { closed: boolean; }
export type CorePortErrorCode =
${tsCodes};
export interface CorePortError { code: CorePortErrorCode; message: string; retryable: boolean; }
export interface CorePort {
  openGraph(request: OpenGraphRequest): Promise<OpenGraphResponse>;
  execute(request: ExecuteRequest): Promise<ExecuteResponse>;
  read(request: ReadRequest): Promise<ReadResponse>;
  readOutline(request: ReadOutlineRequest): Promise<ReadOutlineResponse>;
  query(request: QueryRequest): Promise<QueryResponse>;
  subscribe(request: SubscribeRequest): Promise<SubscribeResponse>;
  closeGraph(request: CloseGraphRequest): Promise<CloseGraphResponse>;
}
`;

const graphSchemaRust = `// @generated by scripts/generate-contracts.mjs; do not edit.

/// Graph document schema accepted and written by this build.
pub const SCHEMA_VERSION: u32 = ${graphSchema.current};
`;

const graphSchemaTypescript = `// @generated by scripts/generate-contracts.mjs; do not edit.
export const SCHEMA_VERSION = ${graphSchema.current} as const;
`;

const syncProtocolRust = `// @generated by scripts/generate-contracts.mjs; do not edit.

/// Application protocol version negotiated in \`Hello\`.
pub const PROTOCOL_VERSION: u16 = ${syncProtocol.protocolVersion};
/// WebSocket application subprotocol clients advertise and the server selects.
pub const SUBPROTOCOL: &str = "${subprotocol}";
`;

const syncProtocolTypescript = `// @generated by scripts/generate-contracts.mjs; do not edit.
export const PROTOCOL_VERSION = ${syncProtocol.protocolVersion} as const;
export const SUBPROTOCOL = "${subprotocol}" as const;
`;

const outputs = [
  ["crates/domain/src/generated/core_port.rs", corePortRust],
  ["apps/client/src/generated/core-port.ts", corePortTypescript],
  ["crates/domain/src/generated/graph_schema.rs", graphSchemaRust],
  ["apps/client/src/generated/graph-schema.ts", graphSchemaTypescript],
  ["crates/sync-protocol/src/generated/wire.rs", syncProtocolRust],
  ["apps/client/src/generated/sync-protocol.ts", syncProtocolTypescript],
];

const stale = [];
for (const [path, content] of outputs) {
  const current = await readFile(path, "utf8").catch(() => "");
  if (current !== content) stale.push([path, content]);
}

if (check && stale.length > 0) {
  throw new Error(
    `generated contract files are stale (${stale.map(([path]) => path).join(", ")}); run devenv tasks run contracts:generate`,
  );
}
if (!check) {
  await Promise.all(stale.map(([path, content]) => writeFile(path, content)));
}
