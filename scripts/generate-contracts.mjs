import { readFile, writeFile } from "node:fs/promises";

const schema = JSON.parse(await readFile("contracts/core-port.json", "utf8"));
const version = schema.contractVersion;

const rust = `// @generated by scripts/generate-contracts.mjs; do not edit.\n\
use serde::{Deserialize, Serialize};\n\n\
pub const CORE_PORT_VERSION: u32 = ${version};\n\n\
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]\n\
pub struct PingRequest {\n\
    pub client_version: String,\n\
}\n\n\
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]\n\
pub struct PingResponse {\n\
    pub contract_version: u32,\n\
    pub core_version: String,\n\
    pub echo: String,\n\
}\n`;

const typescript = `// @generated by scripts/generate-contracts.mjs; do not edit.\n\
export const CORE_PORT_VERSION = ${version} as const;\n\n\
export interface PingRequest {\n\
  client_version: string;\n\
}\n\n\
export interface PingResponse {\n\
  contract_version: number;\n\
  core_version: string;\n\
  echo: string;\n\
}\n`;

await writeFile("crates/domain/src/generated/core_port.rs", rust);
await writeFile("apps/client/src/generated/core-port.ts", typescript);

